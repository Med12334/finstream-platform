CREATE TABLE SETTLEMENT_AUDIT_LOG (
    AUDIT_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    ORDER_ID VARCHAR(36) NOT NULL,
    ACCOUNT_ID VARCHAR(32) NOT NULL,
    SETTLED_AMOUNT DECIMAL(18, 2) NOT NULL,
    EXECUTION_FEE DECIMAL(10, 2) NOT NULL,
    SETTLEMENT_STATUS VARCHAR(24) NOT NULL,
    KAFKA_OFFSET BIGINT NOT NULL,
    KAFKA_PARTITION INT NOT NULL,
    SETTLED_AT TIMESTAMP NOT NULL
);

CREATE INDEX IDX_AUDIT_ORDER ON SETTLEMENT_AUDIT_LOG(ORDER_ID);
